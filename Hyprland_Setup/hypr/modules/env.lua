-- NVIDIA. Applied only when the boot GPU is an NVIDIA card, read from sysfs
-- rather than committed, because this file deploys to every machine: on one
-- without NVIDIA, LIBVA_DRIVER_NAME=nvidia breaks hardware video decode and
-- __GLX_VENDOR_LIBRARY_NAME=nvidia breaks every GLX app.
--
-- "Boot GPU", not "an NVIDIA card is present": on a hybrid laptop the iGPU
-- drives the panel and the dGPU sleeps, and forcing both onto NVIDIA there is
-- the wrong answer. boot_vga is 1 on exactly the card the firmware brought the
-- console up on -- the one with the displays -- and missing or 0 on the rest.
--
-- The card index is assigned in probe order and moves between boots, so a
-- fixed range is probed rather than a name (Lua has no readdir).
--
-- GBM_BACKEND and NVD_BACKEND are deliberately absent: Mesa's GBM loader finds
-- NVIDIA's backend on its own (and forcing it crashes Firefox), and "direct" is
-- already libva-nvidia-driver's default.
local function read_line(path)
	local f = io.open(path, "r")
	if not f then
		return nil
	end
	local line = f:read("l")
	f:close()
	return line
end

local function boot_gpu_is_nvidia()
	for card = 0, 7 do
		local dev = "/sys/class/drm/card" .. card .. "/device/"
		if read_line(dev .. "boot_vga") == "1" then
			return read_line(dev .. "vendor") == "0x10de"
		end
	end
	return false
end

if boot_gpu_is_nvidia() then
	hl.env("LIBVA_DRIVER_NAME", "nvidia")
	hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")
end

